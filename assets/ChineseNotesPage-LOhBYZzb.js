<div class="warn"><b>Bẫy hay gặp:</b> ghép chéo <s>只要…才</s> hoặc <s>只有…就</s>. Nhớ cặp: <b>只要 đi với 就</b> (dễ, chỉ cần), <b>只有 đi với 才</b> (khó, bắt buộc). Với 除了: vế sau dùng 还/也 là <b>cộng thêm</b>, dùng 都 là <b>loại trừ</b>.</div>
