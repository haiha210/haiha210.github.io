<h3>1.4 Pinyin — phần vần (vận mẫu) và quy tắc viết<a class="anch" href="#c1-4">#</a></h3>
<table>
<thead><tr><th>Vần</th><th>Đọc gần giống</th><th>Ví dụ</th></tr></thead>
